export function PageLoader({ progress }: { progress: number }) {
  const [show, setShow] = React.useState(true);
  const [minTimeElapsed, setMinTimeElapsed] = React.useState(false);
  const visualRef = React.useRef(0);
  const [visualProgress, setVisualProgress] = React.useState(0);

  React.useEffect(() => {
    const timer = setTimeout(() => setMinTimeElapsed(true), 1500);
    return () => clearTimeout(timer);
  }, []);

  React.useEffect(() => {
    let raf: number;
    const animate = () => {
      const diff = progress - visualRef.current;
      if (diff > 0.1) {
        visualRef.current += diff * 0.08;
        setVisualProgress(visualRef.current);
        raf = requestAnimationFrame(animate);
      } else {
        visualRef.current = progress;
        setVisualProgress(progress);
      }
    };
    raf = requestAnimationFrame(animate);
    return () => cancelAnimationFrame(raf);
  }, [progress]);

  React.useEffect(() => {
    if (minTimeElapsed && progress === 100 && visualProgress >= 99.5) {
      const t = setTimeout(() => setShow(false), 200);
      return () => clearTimeout(t);
    }
  }, [minTimeElapsed, progress, visualProgress]);

  if (!show) return null;

  const isHidden = minTimeElapsed && progress === 100 && visualProgress >= 99.5;

  return (
    <div className={`${styles.overlay} ${isHidden ? styles.hidden : styles.visible}`}>
      <div className={styles.content}>

        <Logo />

        <div className={styles.skyLabel}>Sky Gallery</div>

        <div className={styles.progressBarContainer}>
          <div
            className={styles.progressBarFill}
            style={{ transform: `scaleX(${visualProgress / 100})` }}
          />
        </div>

        <div className={styles.controls}>
          <div className={styles.crossGrid}>
            <div className={styles.crossEmpty} />
            <div className={styles.keySquare}><ArrowUp /></div>
            <div className={styles.crossEmpty} />

            <div className={styles.keySquare}><ArrowLeft /></div>
            <div className={styles.keySquare}><ScrollIcon /></div>
            <div className={styles.keySquare}><ArrowRight /></div>

            <div className={styles.crossEmpty} />
            <div className={styles.keySquare}><ArrowDown /></div>
            <div className={styles.crossEmpty} />
          </div>

          <p className={styles.hint}>click on artworks to view</p>
        </div>

      </div>
    </div>
  );
}
